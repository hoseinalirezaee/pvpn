// Package render makes the text of the files that pvpn owns: the netplan file,
// the wg-quick files, and the systemd drop-ins. All functions are pure.
package render

import (
	"fmt"
	"net/netip"
	"sort"
	"strings"
)

// Fixed values of the Proton WireGuard service.
const (
	TunnelIPv4   = "10.2.0.2/32"
	TunnelIPv6   = "2a07:b944::2:2/128"
	TunnelGWv4   = "10.2.0.1"
	EndpointPort = 51820
	Keepalive    = 25
)

// ManagedHeader is the first line of every file pvpn owns (wg-quick form).
const ManagedHeader = "# managed-by = pvpn"

// NetplanHeader is the first line of the managed netplan file.
const NetplanHeader = "# managed-by: pvpn"

// Member is the netplan part of one interface.
type Member struct {
	Iface    string
	Table    int
	Mark     int
	Priority int
	Addrs    []netip.Addr // every address netplan must keep for this interface
	From     netip.Addr   // preferred source of the table route
	Gateway  netip.Addr
}

// Device is a netplan device definition with its pvpn members.
type Device struct {
	Section string // netplan section, for example "ethernets"
	ID      string // netplan ID of the device
	Members []Member
}

// Netplan renders /etc/netplan/90-pvpn.yaml. It returns nil when no member exists.
func Netplan(devs []Device) []byte {
	var ds []Device
	for _, d := range devs {
		if len(d.Members) > 0 {
			ds = append(ds, d)
		}
	}
	if len(ds) == 0 {
		return nil
	}
	sort.Slice(ds, func(i, j int) bool {
		if ds[i].Section != ds[j].Section {
			return ds[i].Section < ds[j].Section
		}
		return ds[i].ID < ds[j].ID
	})
	var b strings.Builder
	b.WriteString(NetplanHeader + "\n# Generated by pvpn. Do not edit. `pvpn reconcile` rewrites this file.\n")
	b.WriteString("network:\n  version: 2\n")
	for i := 0; i < len(ds); {
		sec := ds[i].Section
		fmt.Fprintf(&b, "  %s:\n", sec)
		for ; i < len(ds) && ds[i].Section == sec; i++ {
			d := ds[i]
			ms := append([]Member(nil), d.Members...)
			sort.Slice(ms, func(a, c int) bool { return ms[a].Iface < ms[c].Iface })
			fmt.Fprintf(&b, "    %s:\n", yamlStr(d.ID))
			b.WriteString("      addresses:\n")
			for _, m := range ms {
				addrs := make([]string, len(m.Addrs))
				for k, a := range m.Addrs {
					addrs[k] = a.String()
				}
				sort.Strings(addrs)
				for _, a := range addrs {
					fmt.Fprintf(&b, "        - \"%s/128\":\n            lifetime: 0\n", a)
				}
			}
			b.WriteString("      routes:\n")
			for _, m := range ms {
				fmt.Fprintf(&b, "        - to: \"::/0\"\n          via: \"%s\"\n          from: \"%s\"\n          table: %d\n          on-link: true\n", m.Gateway, m.From, m.Table)
			}
			b.WriteString("      routing-policy:\n")
			for _, m := range ms {
				fmt.Fprintf(&b, "        - to: \"::/0\"\n          mark: %d  # 0x%x\n          table: %d\n          priority: %d\n", m.Mark, m.Mark, m.Table, m.Priority)
			}
		}
	}
	return []byte(b.String())
}

func yamlStr(s string) string {
	if strings.IndexFunc(s, func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_' || r == '-' || r == '.')
	}) >= 0 {
		return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
	}
	return s
}

// WG holds the values of one wg-quick file.
type WG struct {
	Iface         string
	Group         string
	Server        string // logical server name, for example DE#520
	PrivateKey    string
	Mark          int
	Device        string
	SourceIP      netip.Addr
	PeerPublicKey string
	Endpoint      netip.Addr // IPv6 entry address
}

// PreUp returns the one startup command in the file. Netplan owns the address, the route, and the rule.
// This command only restores the noprefixroute flag, which netplan cannot set.
func PreUp(dev string, src netip.Addr) string {
	return fmt.Sprintf("ip -6 addr change %s/128 dev %s noprefixroute preferred_lft 0", src, dev)
}

// WireGuard renders /etc/wireguard/<iface>.conf.
func WireGuard(w WG) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s\n# group = %s\n# server = %s\n\n", ManagedHeader, w.Group, w.Server)
	b.WriteString("[Interface]\n")
	fmt.Fprintf(&b, "PrivateKey = %s\n", w.PrivateKey)
	fmt.Fprintf(&b, "Address = %s, %s\n", TunnelIPv4, TunnelIPv6)
	b.WriteString("Table = off\n")
	fmt.Fprintf(&b, "FwMark = 0x%x\n", w.Mark)
	b.WriteString("SaveConfig = false\n")
	fmt.Fprintf(&b, "PreUp = %s\n\n", PreUp(w.Device, w.SourceIP))
	b.WriteString("[Peer]\n")
	fmt.Fprintf(&b, "PublicKey = %s\n", w.PeerPublicKey)
	fmt.Fprintf(&b, "Endpoint = [%s]:%d\n", w.Endpoint, EndpointPort)
	b.WriteString("AllowedIPs = 0.0.0.0/0, ::/0\n")
	fmt.Fprintf(&b, "PersistentKeepalive = %d\n", Keepalive)
	return b.String()
}

// WGMeta is what pvpn reads back from a file it wrote.
type WGMeta struct {
	Managed    bool
	Group      string
	Server     string
	PrivateKey string
	PeerKey    string
	Endpoint   string
}

// ParseWG reads the header and the keys of a wg-quick file.
func ParseWG(text string) WGMeta {
	var m WGMeta
	lines := strings.Split(strings.ReplaceAll(text, "\r", ""), "\n")
	if len(lines) > 0 && strings.TrimSpace(lines[0]) == ManagedHeader {
		m.Managed = true
	}
	for _, ln := range lines {
		t := strings.TrimSpace(ln)
		if v, ok := strings.CutPrefix(t, "# group = "); ok {
			m.Group = v
		} else if v, ok := strings.CutPrefix(t, "# server = "); ok {
			m.Server = v
		}
		k, v, ok := strings.Cut(t, "=")
		if !ok || strings.HasPrefix(t, "#") {
			continue
		}
		v = strings.TrimSpace(v)
		switch strings.TrimSpace(k) {
		case "PrivateKey":
			m.PrivateKey = v
		case "PublicKey":
			m.PeerKey = v
		case "Endpoint":
			m.Endpoint = v
		}
	}
	return m
}

// DropIn is the systemd drop-in for wg-quick@<iface>.service. It orders the unit after
// a successful systemd-networkd-wait-online run, so source addresses exist at boot.
func DropIn() string {
	return "# managed-by = pvpn\n" +
		"[Unit]\n" +
		"Wants=network-online.target\n" +
		"After=network-online.target systemd-networkd-wait-online.service\n" +
		"Requires=systemd-networkd-wait-online.service\n"
}
